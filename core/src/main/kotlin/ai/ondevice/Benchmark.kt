package ai.ondevice

import kotlin.math.ceil

/**
 * Structured benchmark reporting for the on-device core.
 *
 * The demo's `benchmark` command used to print only mean/p50 latency.
 * A benchmark a hiring manager can trust needs the tail (p95/p99, so a
 * stuttery phone is visible), accuracy *per label* (so one weak class
 * cannot hide behind a good average), and a model-size breakdown (so the
 * int8 size win is auditable layer by layer). This module computes all
 * three from one run and renders them as Markdown for `docs/benchmarks.md`.
 */

/** Latency distribution over one timed run set, in milliseconds. */
data class LatencyStats(
    val runs: Int,
    val meanMs: Double,
    val p50Ms: Double,
    val p95Ms: Double,
    val p99Ms: Double,
    val minMs: Double,
    val maxMs: Double,
) {
    /** Inferences per second implied by the mean latency. */
    val throughputPerSec: Double get() = if (meanMs > 0) 1000.0 / meanMs else 0.0
}

/** Nearest-rank percentile over a sorted array (p in 0..100). */
private fun percentile(sorted: DoubleArray, p: Double): Double {
    require(sorted.isNotEmpty()) { "percentile needs at least one sample" }
    val rank = ceil(p / 100.0 * sorted.size).toInt().coerceIn(1, sorted.size)
    return sorted[rank - 1]
}

/** Summarize raw per-inference latencies (ms) into a [LatencyStats]. */
fun latencyStats(times: DoubleArray): LatencyStats {
    require(times.isNotEmpty()) { "latencyStats needs at least one timing" }
    val sorted = times.sortedArray()
    return LatencyStats(
        runs = times.size,
        meanMs = times.average(),
        p50Ms = percentile(sorted, 50.0),
        p95Ms = percentile(sorted, 95.0),
        p99Ms = percentile(sorted, 99.0),
        minMs = sorted.first(),
        maxMs = sorted.last(),
    )
}

/** Accuracy for one label: correct predictions over that label's examples. */
data class LabelAccuracy(val label: String, val correct: Int, val total: Int) {
    val accuracy: Double get() = if (total == 0) 0.0 else correct.toDouble() / total
}

/**
 * Per-label accuracy for any predictor over a labelled set. Labels with
 * no examples report total 0 and accuracy 0.0 rather than crashing, so a
 * skewed test set degrades visibly instead of blowing up the report.
 */
fun perLabelAccuracy(
    predict: (FloatArray) -> Int,
    xs: List<FloatArray>,
    ys: IntArray,
    labels: List<String>,
): List<LabelAccuracy> {
    require(xs.size == ys.size) { "inputs and labels must align" }
    val correct = IntArray(labels.size)
    val total = IntArray(labels.size)
    for (i in xs.indices) {
        val truth = ys[i]
        require(truth in labels.indices) { "label index $truth out of range" }
        total[truth]++
        if (predict(xs[i]) == truth) correct[truth]++
    }
    return labels.mapIndexed { idx, label -> LabelAccuracy(label, correct[idx], total[idx]) }
}

/** Weight size of one layer in both precisions (biases stay float in both). */
data class LayerSize(
    val index: Int,
    val rows: Int,
    val cols: Int,
    val floatBytes: Long,
    val int8Bytes: Long,
)

/** Per-layer weight sizes for an [Mlp]; layer 0 is the input layer. */
fun modelSizeBreakdown(mlp: Mlp): List<LayerSize> =
    mlp.layers.mapIndexed { idx, layer ->
        LayerSize(idx, layer.outputSize, layer.inputSize, layer.outputSize.toLong() * layer.inputSize * 4L, layer.outputSize.toLong() * layer.inputSize)
    }

/** One complete benchmark run: latency, accuracy and size, float vs int8. */
data class BenchmarkReport(
    val modelShape: String,
    val runs: Int,
    val testSize: Int,
    val floatLatency: LatencyStats,
    val int8Latency: LatencyStats,
    val floatAccuracy: Double,
    val int8Accuracy: Double,
    val floatPerLabel: List<LabelAccuracy>,
    val int8PerLabel: List<LabelAccuracy>,
    val layers: List<LayerSize>,
) {
    val floatWeightBytes: Long get() = layers.sumOf { it.floatBytes }
    val int8WeightBytes: Long get() = layers.sumOf { it.int8Bytes }
    val sizeRatio: Double get() = if (int8WeightBytes == 0L) 0.0 else floatWeightBytes.toDouble() / int8WeightBytes

    private fun latencyRow(name: String, s: LatencyStats): String =
        "| $name | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f | %.0f |".format(
            s.meanMs, s.p50Ms, s.p95Ms, s.p99Ms, s.minMs, s.maxMs, s.throughputPerSec,
        )

    /** Render the report as Markdown (the format committed to docs/benchmarks.md). */
    fun toMarkdown(): String {
        val sb = StringBuilder()
        sb.appendLine("# Benchmark report")
        sb.appendLine()
        sb.appendLine("Model: $modelShape. Latency over $runs runs per precision (first run discarded as warm-up).")
        sb.appendLine("Accuracy over $testSize held-out examples. Generated by `demo benchmark --report <path>`.")
        sb.appendLine()
        sb.appendLine("## Latency (ms)")
        sb.appendLine()
        sb.appendLine("| Precision | Mean | p50 | p95 | p99 | Min | Max | Throughput (inf/s) |")
        sb.appendLine("| --- | --- | --- | --- | --- | --- | --- | --- |")
        sb.appendLine(latencyRow("float32", floatLatency))
        sb.appendLine(latencyRow("int8", int8Latency))
        sb.appendLine()
        sb.appendLine("## Accuracy")
        sb.appendLine()
        sb.appendLine("| Label | float32 | int8 | Examples |")
        sb.appendLine("| --- | --- | --- | --- |")
        for (i in floatPerLabel.indices) {
            val f = floatPerLabel[i]
            val q = int8PerLabel[i]
            sb.appendLine("| ${f.label} | %.3f | %.3f | ${f.total} |".format(f.accuracy, q.accuracy))
        }
        sb.appendLine("| **Overall** | %.3f | %.3f | $testSize |".format(floatAccuracy, int8Accuracy))
        sb.appendLine()
        sb.appendLine("## Model size (weights only, biases stay float in both)")
        sb.appendLine()
        sb.appendLine("| Layer | Shape | float32 (bytes) | int8 (bytes) |")
        sb.appendLine("| --- | --- | --- | --- |")
        for (layer in layers) {
            sb.appendLine("| ${layer.index} | ${layer.rows}x${layer.cols} | ${layer.floatBytes} | ${layer.int8Bytes} |")
        }
        sb.appendLine("| **Total** | | **$floatWeightBytes** | **$int8WeightBytes** |")
        sb.appendLine()
        sb.appendLine("int8 is %.1fx smaller than float32.".format(sizeRatio))
        sb.appendLine()
        sb.appendLine("Honest note: on the JVM the int8 path is usually *not* faster — integer math")
        sb.appendLine("without SIMD plus per-call input quantization costs more than it saves at this")
        sb.appendLine("model size. The int8 win here is the smaller model (APK size, memory, download)")
        sb.appendLine("and suitability for phone DSP/NPU kernels, where the integer path is what runs fast.")
        return sb.toString()
    }
}

/**
 * Run a full benchmark: timed inference in both precisions plus accuracy
 * (overall and per label) and the size breakdown, all from one classifier.
 */
fun runBenchmark(
    classifier: OnDeviceClassifier,
    sample: FloatArray,
    testX: List<FloatArray>,
    testY: IntArray,
    runs: Int = 200,
): BenchmarkReport {
    require(runs > 0) { "runs must be positive" }
    classifier.useQuantized = false
    val floatLatency = latencyStats(classifier.benchmarkTimes(sample, runs))
    classifier.useQuantized = true
    val int8Latency = latencyStats(classifier.benchmarkTimes(sample, runs))
    val floatPerLabel = perLabelAccuracy(classifier.floatMlp::predict, testX, testY, classifier.labels)
    val int8PerLabel = perLabelAccuracy(classifier.quantizedMlp::predict, testX, testY, classifier.labels)
    val floatAccuracy = accuracy(classifier.floatMlp, testX, testY).toDouble()
    val int8Accuracy = accuracy(classifier.quantizedMlp, testX, testY).toDouble()
    val shape = classifier.floatMlp.layers.joinToString(" -> ") { "${it.inputSize}" } +
        " -> ${classifier.floatMlp.layers.last().outputSize}"
    return BenchmarkReport(
        modelShape = shape,
        runs = runs,
        testSize = testX.size,
        floatLatency = floatLatency,
        int8Latency = int8Latency,
        floatAccuracy = floatAccuracy,
        int8Accuracy = int8Accuracy,
        floatPerLabel = floatPerLabel,
        int8PerLabel = int8PerLabel,
        layers = modelSizeBreakdown(classifier.floatMlp),
    )
}
